def upsert_opportunity(db: sqlite3.Connection, opp: Dict[str, Any]) -> str:
    """Insert or update an opportunity by slug/title. Returns 'inserted' or 'updated'."""
    row = _normalize_seed(opp)
    cursor = db.cursor()
    cursor.execute(
        "SELECT id FROM opportunities WHERE (slug != '' AND LOWER(slug) = LOWER(?)) OR LOWER(title) = LOWER(?)",
        (row["slug"], row["title"]),
    )
    existing = cursor.fetchone()
    values = tuple(row[c] for c in OPP_COLUMNS)
    if existing:
        assignments = ", ".join(f"{c} = ?" for c in OPP_COLUMNS)
        cursor.execute(
            f"UPDATE opportunities SET {assignments} WHERE id = ?",
            values + (existing[0],),
        )
        return "updated"
    placeholders = ", ".join("?" for _ in OPP_COLUMNS)
    cursor.execute(
        f"INSERT INTO opportunities ({', '.join(OPP_COLUMNS)}) VALUES ({placeholders})",
        values,
    )
    return "inserted"


def seed_opportunities(db: sqlite3.Connection) -> int:
    """
    Upserts the original 17 catalog rows plus the 9 core verified opportunities.
    Safe to run on existing databases.
    """
    changed = 0
    for opp in SEED_OPPORTUNITIES + CORE_OPPORTUNITIES:
        result = upsert_opportunity(db, opp)
        if result == "inserted":
            changed += 1
    db.commit()
    return changed


